package dev.gainsay.core;

/**
 * Proof of mechanism for a finding: <em>what exactly was read or seen</em>, and how a human can
 * reproduce the same observation by hand.
 *
 * @param kind      {@code registry}, {@code wmi}, {@code cmdlet}, {@code command}, {@code packet},
 *                  {@code scan} or {@code trial}
 * @param source    where it was read: a registry path, a WMI class, a cmdlet, or a flow
 *                  ({@code 10.0.0.5:445 -> 10.0.0.9:51544}, frame number)
 * @param detail    the value or field that triggered the finding (always redacted and bounded)
 * @param reproduce a one-liner to verify by hand (PowerShell for host evidence, a tshark display
 *                  filter for packet evidence); may be null
 */
public record Evidence(String kind, String source, String detail, String reproduce) {

    public Evidence {
        source = Redactor.sanitize(source);
        detail = Redactor.sanitize(detail);
        // reproduce snippets are generated by Gainsay itself from fixed templates; still bound them.
        reproduce = reproduce == null ? null : (reproduce.length() > 600 ? reproduce.substring(0, 600) : reproduce);
    }

    public static Evidence of(String kind, String source, String detail) {
        return new Evidence(kind, source, detail, null);
    }
}
